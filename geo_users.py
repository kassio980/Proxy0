def geoip(ip):
    """Retorna país, lat, lon, nome, bandeira. 100% offline, sem API externa."""
    if not ip: return GEO["local"]
    for cod, g in GEO.items():
        for f in g["fx"]:
            if ip.startswith(f):
                jitter_lat = random.uniform(-2.5,2.5)
                jitter_lon = random.uniform(-3.5,3.5)
                return {
                    "cod": cod, "nome": g["n"], "flag": g["f"],
                    "lat": round(g["c"][0]+jitter_lat,3),
                    "lon": round(g["c"][1]+jitter_lon,3),
                    "ip": ip
                }
    # Fallback: BR
    return {"cod":"br","nome":"Brasil","flag":"🇧🇷","lat":-15+random.uniform(-4,4),"lon":-52+random.uniform(-6,6),"ip":ip}

class Usuarios:
    def __init__(self):
        self.dados = {}
        self.historico = deque(maxlen=200)
        self.por_pais = defaultdict(int)
        self._carregar()

    def _carregar(self):
        try:
            if os.path.exists(DB_PATH):
                d = json.load(open(DB_PATH))
                self.dados = d.get("dados",{})
                self.historico = deque(d.get("historico",[]), maxlen=200)
                self.por_pais = defaultdict(int, d.get("por_pais",{}))
        except: pass

    def _salvar(self):
        try:
            os.makedirs(os.path.dirname(DB_PATH),exist_ok=True)
            json.dump({
                "dados":dict(list(self.dados.items())[-500:]),
                "historico":list(self.historico),
                "por_pais":dict(self.por_pais)
            }, open(DB_PATH,"w"), indent=2, ensure_ascii=False)
        except: pass

    def registrar(self, ip, servidor_ff=None, tipo="TCP"):
        """Registra um usuário novo conectando"""
        if not ip: return None
        g = geoip(ip)
        agora = time.time()
        self.dados[ip] = {
            **g,
            "servidor": servidor_ff,
            "tipo": tipo,
            "primeira": self.dados.get(ip,{}).get("primeira",agora),
            "ultima": agora,
            "pacotes": self.dados.get(ip,{}).get("pacotes",0)+1
        }
        self.por_pais[g["cod"]] += 1
        self.historico.appendleft({
            "t": datetime_string(), **g,
            "servidor": servidor_ff, "tipo": tipo
        })
        threading.Thread(target=self._salvar,daemon=True).start()
        return self.dados[ip]

    def desconectar(self, ip):
        if ip in self.dados:
            self.dados[ip]["offline"] = time.time()

    def top_paises(self, n=15):
        return sorted(self.por_pais.items(), key=lambda x:-x[1])[:n]

    def todos_online(self, max_age_seg=300):
        """Só quem viu nos últimos 5 min"""
        agora = time.time()
        return [u for u in self.dados.values() if agora - u.get("ultima",0) < max_age_seg]

    def resumo(self):
        on = self.todos_online()
        return {
            "online": len(on),
            "total": len(self.dados),
            "paises": len(self.por_pais),
            "top": [{"p":GEO.get(cod,{"n":cod,"f":"🌍"})["n"],"f":GEO.get(cod,{"f":"🌍"})["f"],"q":q} for cod,q in self.top_paises()],
            "ultimos": list(self.historico)[:20],
            "mapa": [{"lat":u["lat"],"lon":u["lon"],"f":u["flag"],"n":u["nome"],"ip":u["ip"],"s":u.get("servidor")} for u in on]
        }

def datetime_string():
    return time.strftime("%H:%M:%S %d/%m")

